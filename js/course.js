export const COURSE = [];
let index = 0;
for (const [u, unit] of units.entries()) {
  for (const [l, lesson] of unit.lessons.entries()) {
    COURSE.push({
      id: `u${u + 1}l${l + 1}`,
      index: index++,
      unit: u,
      unitTitle: unit.title,
      who: unit.who,
      title: lesson.title,
      tip: lesson.tip,
      items: lesson.items.map(([en, ru, pron]) => ({ en, ru, pron })),
      dialog: lesson.dialog,
    });
  }
}

export const UNITS = units.map((unit, i) => ({
  title: unit.title,
  lessons: COURSE.filter((lesson) => lesson.unit === i),
}));

export const ALL_ITEMS = COURSE.flatMap((lesson) => lesson.items);
